"""Design tokens — the single source of truth for visual values (spec §24).

Tokens are plain Python constants; `theme/tokens_qss.py` compiles them into
Qt palettes + QSS. Nothing in the UI may hard-code a colour/spacing value that
has a token equivalent.
"""
