# ------------------------------------------------------------- typography
@dataclass(frozen=True)
class Typography:
    family_ui: str = "Segoe UI"
    family_fallbacks: tuple[str, ...] = ("Inter", "Noto Sans", "sans-serif")
    size_caption: int = 11
    size_body: int = 13
    size_control: int = 13
    size_subhead: int = 15
    size_headline: int = 20
    size_display: int = 28
    size_timer: int = 34
    weight_regular: int = 400
    weight_semibold: int = 600
    weight_bold: int = 700


TYPOGRAPHY = Typography()


def font_stack() -> str:
    return ", ".join((TYPOGRAPHY.family_ui,) + TYPOGRAPHY.family_fallbacks)


# ------------------------------------------------------------------ colours
@dataclass(frozen=True)
class Palette:
    # base surfaces (dark theme is primary)
    bg_root: str = "#0B0E13"          # app background
    bg_surface: str = "#12161D"       # cards / panels
    bg_raised: str = "#171C25"        # elevated controls
    bg_input: str = "#0E1218"
    bg_overlay: str = "#0B0E13"       # modals/toasts (with alpha applied)

    # borders & dividers
    border_subtle: str = "#222A35"
    border_strong: str = "#2E3947"
    divider: str = "#1A212B"

    # text
    text_primary: str = "#E8EDF4"
    text_secondary: str = "#9AA7B8"
    text_muted: str = "#5F6C7D"
    text_inverse: str = "#0B0E13"

    # accents (restrained: gold is the brand, blue is informational)
    accent_gold: str = "#C89B3C"
    accent_gold_soft: str = "#8A6B2A"
    accent_blue: str = "#0AC8B9"      # hextech teal for interactive highlight
    accent_hover: str = "#1FD8C8"

    # semantic
    ok: str = "#3DD68C"
    info: str = "#0AC8B9"
    warn: str = "#E8B23A"
    error: str = "#F0524F"
    danger: str = "#FF4B47"           # emergency stop only
    disabled_fg: str = "#4A5563"
    disabled_bg: str = "#141922"

    # state dot colours (paired with glyphs so meaning never relies on hue alone)
    dot_connected: str = "#3DD68C"
    dot_searching: str = "#0AC8B9"
    dot_champ_select: str = "#C89B3C"
    dot_disconnected: str = "#F0524F"
    dot_stale: str = "#E8B23A"


